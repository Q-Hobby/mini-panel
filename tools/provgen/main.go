// Command provgen writes internal/cloudprov/generated.go: the form of every storage rclone has that the panel has no form of its own
// for. It reads rclone's list of options for each backend imported by internal/remote and keeps the basic, visible ones that neither
// run a command nor read a file of this machine. Run it after an rclone upgrade:
//
//	go run ./tools/provgen > internal/cloudprov/generated.go && gofmt -w internal/cloudprov/generated.go
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"github.com/rclone/rclone/fs"

	"mpn/internal/cloudprov"
	_ "mpn/internal/remote"
)

// skip are backends imported for completeness that are not a storage of their own, plus the old name of storj.
var skip = map[string]bool{"local": true, "tardigrade": true, "crypt": true, "alias": true, "union": true, "combine": true, "chunker": true,
	"hasher": true, "compress": true, "cache": true, "archive": true, "memory": true, "http": true, "doi": true, "google photos": true}

// secret says whether a box hides what is typed and the value is never shown again. rclone marks many plain names (an account, a
// tenant ID) Sensitive only so that they are left out of logs; those stay visible.
func secret(o fs.Option) bool {
	if o.IsPassword || o.Name == "token" {
		return true
	}
	n := o.Name
	for _, w := range []string{"secret", "password", "pass", "token", "key", "grant", "sas_url", "connection_string", "passphrase"} {
		if strings.Contains(n, w) && n != "key_id" && !strings.HasSuffix(n, "_key_id") && n != "public_key" {
			return true
		}
	}
	return false
}

// drop are options that are visible in rclone's basic form but make no sense for the panel: they choose a way of signing in that reads
// this machine (azure's MSI and CLI, a certificate path), or are switches of the interactive setup.
var drop = map[string]bool{
	"env_auth": true, "use_msi": true, "use_az": true, "use_emulator": true, "client_certificate_path": true,
	"client_certificate_password": true, "box_config_file": true, "service_account_file": true, "nounc": true,
	"use_kerberos": true, "anonymous": true, "description": true,
}

// keepAdvanced are advanced options the panel offers anyway, because some accounts cannot connect without them.
var keepAdvanced = map[string]bool{"endpoint": true, "region": true, "token": true, "root_folder_id": true, "drive_id": true, "drive_type": true, "hard_delete": true}

func firstLine(s string) string {
	s = strings.TrimSpace(s)
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		s = s[:i]
	}
	return strings.TrimSuffix(strings.TrimSpace(s), ".")
}

func main() {
	curated := map[string]bool{}
	for _, p := range cloudprov.Providers {
		if !p.Generated {
			curated[p.Type] = true
		}
	}
	regs := append([]*fs.RegInfo(nil), fs.Registry...)
	sort.Slice(regs, func(i, j int) bool { return regs[i].Name < regs[j].Name })
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/provgen from rclone's list of options; DO NOT EDIT.\n\npackage cloudprov\n\nvar generated = []Provider{\n")
	for _, ri := range regs {
		if curated[ri.Name] || skip[ri.Name] {
			continue
		}
		typ := ri.Name // "google cloud storage" is the type written in rclone.conf, spaces and all
		oauth := false
		seen := map[string]bool{}
		var fields []string
		for _, o := range ri.Options {
			if o.Name == "token" && ri.Config != nil {
				oauth = true
			}
		}
		for _, o := range ri.Options {
			if seen[o.Name] || drop[o.Name] || cloudprov.Dangerous(o.Name) || o.Hide&fs.OptionHideConfigurator != 0 {
				continue
			}
			if o.Advanced && !keepAdvanced[o.Name] {
				continue
			}
			// The client ID and secret of an OAuth storage are optional: rclone has its own, and the token pasted from
			// "rclone authorize" was made with those.
			if oauth && (o.Name == "auth_url" || o.Name == "token_url" || o.Name == "client_credentials") {
				continue
			}
			seen[o.Name] = true
			var f []string
			f = append(f, fmt.Sprintf("Key: %q", o.Name))
			if secret(o) {
				f = append(f, "Secret: true")
			}
			// rclone marks options Required for its interactive setup; one that has no default must be given. The token of an
			// OAuth storage is required too: the server has no browser to get one.
			if o.Required && fmt.Sprint(o.Default) == "" && o.Provider == "" || oauth && o.Name == "token" {
				f = append(f, "Required: true")
			}
			if o.Name == "token" {
				f = append(f, "JSON: true")
			}
			if o.Exclusive && len(o.Examples) > 0 {
				var ch []string
				for _, e := range o.Examples {
					ch = append(ch, fmt.Sprintf("%q", e.Value))
				}
				f = append(f, "Choices: []string{"+strings.Join(ch, ", ")+"}")
			} else if len(o.Examples) > 0 && o.Examples[0].Value != "" {
				f = append(f, fmt.Sprintf("Placeholder: %q", o.Examples[0].Value))
			}
			if d := fmt.Sprint(o.Default); o.Default != nil && d != "" && d != "false" && d != "0" && d != "[]" && len(d) < 80 && !strings.ContainsAny(d, "\n\"") {
				if o.Exclusive {
					f = append(f, fmt.Sprintf("Default: %q", d))
				}
			}
			help := firstLine(o.Help)
			if help == "" {
				help = strings.ReplaceAll(o.Name, "_", " ")
			}
			f = append(f, fmt.Sprintf("Help: %q", help))
			fields = append(fields, "{"+strings.Join(f, ", ")+"}")
		}
		if len(fields) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\t{Type: %q, Generated: true, Name: %q, OAuth: %v, Fields: []Field{\n\t\t%s,\n\t}},\n", typ, firstLine(ri.Description), oauth, strings.Join(fields, ",\n\t\t"))
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		os.Stdout.Write(b.Bytes())
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	os.Stdout.Write(out)
}
